// A page in the other language: its words, its pictures, its links. Run at
// build time by scripts/site/pages.mjs, which saves what it shows.
function apply(lang) {
  var L = lang === 'it' ? IT : EN;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-t]').forEach(function (n) { var v = L[n.getAttribute('data-t')]; if (v) n.textContent = v; });
  document.querySelectorAll('[data-t-html]').forEach(function (n) { var v = L[n.getAttribute('data-t-html')]; if (v) n.innerHTML = v; });
  document.querySelectorAll('[data-t-alt]').forEach(function (n) { var v = L[n.getAttribute('data-t-alt')]; if (v) n.setAttribute('alt', v); });
  document.querySelectorAll('[data-shot]').forEach(function (n) { n.src = '/shots/' + lang + '-' + n.getAttribute('data-shot') + '.webp'; });
  document.querySelectorAll('[data-page]').forEach(function (n) {
    var p = PAGES[n.getAttribute('data-page')];
    if (p) n.setAttribute('href', p[lang === 'it' ? 1 : 0] + (n.getAttribute('data-hash') || ''));
  });
}

