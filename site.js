// The bar: on a phone, the links fold into a menu - "Get the app" stays
// in sight on every page, at every scroll.
(function () {
  var bar = document.querySelector('.nav');
  var btn = bar && bar.querySelector('.menu');
  if (!btn) return;
  var set = function (open) { bar.classList.toggle('open', open); btn.setAttribute('aria-expanded', String(open)); };
  btn.addEventListener('click', function () { set(!bar.classList.contains('open')); });
  bar.querySelectorAll('.links a').forEach(function (a) { a.addEventListener('click', function () { set(false); }); });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') set(false); });
  document.addEventListener('click', function (e) { if (!bar.contains(e.target)) set(false); });
  // The page we are on, marked in the bar.
  var here = document.body.getAttribute('data-page');
  bar.querySelectorAll('.links a[data-page="' + here + '"]:not([data-hash])').forEach(function (a) { a.setAttribute('aria-current', 'page'); });
})();

