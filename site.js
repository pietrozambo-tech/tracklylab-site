var CALM = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);

// The strips of screens: the switch above one (or the list beside it)
// scrolls it, scrolling it moves the switch. While a strip is in sight it
// turns by itself every few seconds - until a hand touches it, then never
// again.
var TURN = 5200;
document.querySelectorAll('.swipe').forEach(function (sw) {
  var box = sw.closest('section') || sw;
  var track = sw.querySelector('.track');
  var slides = track.children.length;
  var ctrls = box.querySelectorAll('[data-go]');
  var dots = sw.querySelectorAll('.dots i');
  var at = 0, timer = null, touched = false, heading = null, arrive = null;
  var show = function (n) {
    at = n;
    ctrls.forEach(function (t) { t.setAttribute('aria-selected', String(Number(t.getAttribute('data-go')) === n)); });
    dots.forEach(function (d, k) { d.classList.toggle('on', k === n); });
  };
  // On the way to a screen it was sent to, the strip passes the others: the
  // switch already says where it is going, and does not flicker back.
  var go = function (n) {
    heading = n; clearTimeout(arrive); arrive = setTimeout(function () { heading = null; }, 900);
    track.scrollTo({ left: n * track.clientWidth, behavior: CALM ? 'auto' : 'smooth' }); show(n);
  };
  var stop = function () { touched = true; box.classList.remove('auto'); if (timer) { clearInterval(timer); timer = null; } };
  ctrls.forEach(function (t) {
    t.addEventListener('click', function () { stop(); go(Number(t.getAttribute('data-go'))); });
  });
  ['pointerdown', 'touchstart', 'wheel', 'keydown'].forEach(function (e) { sw.addEventListener(e, function () { heading = null; stop(); }, { passive: true }); });
  track.addEventListener('scroll', function () {
    var n = Math.round(track.scrollLeft / Math.max(1, track.clientWidth));
    if (heading !== null) { if (n === heading) heading = null; return; }
    if (n !== at) show(n);
  }, { passive: true });
  if (CALM || !('IntersectionObserver' in window)) return;
  box.style.setProperty('--turn', TURN + 'ms');
  new IntersectionObserver(function (es) {
    es.forEach(function (e) {
      if (e.isIntersecting && !touched && !timer) {
        box.classList.add('auto');
        // Restart the bar under the chosen item, in step with the turn.
        show(at);
        timer = setInterval(function () { go((at + 1) % slides); }, TURN);
      } else if (!e.isIntersecting && timer) { clearInterval(timer); timer = null; box.classList.remove('auto'); }
    });
  }, { threshold: 0.55 }).observe(track);
});

// A list that picks the phone's screen: the open item keeps the height of
// the longest text, so the words around it never move as it turns.
(function () {
  var fit = function () {
    document.querySelectorAll('.picks').forEach(function (box) {
      var h = 0;
      box.style.removeProperty('--pbh');
      box.querySelectorAll('.pb > span').forEach(function (n) { h = Math.max(h, n.scrollHeight); });
      if (h) box.style.setProperty('--pbh', h + 'px');
    });
  };
  fit();
  window.addEventListener('resize', fit);
  window.addEventListener('load', fit);
})();

// The sub-tabs of the Features page: the section on screen is the one lit,
// and the row scrolls to keep it in view.
(function () {
  var sub = document.querySelector('.subnav');
  if (!sub || !('IntersectionObserver' in window)) return;
  var links = sub.querySelectorAll('a[href^="#"]');
  var byId = {};
  links.forEach(function (a) { byId[a.getAttribute('href').slice(1)] = a; });
  var light = function (id) {
    links.forEach(function (a) { a.classList.toggle('on', a === byId[id]); });
    var a = byId[id];
    if (a) sub.querySelector('.row').scrollTo({ left: a.offsetLeft - 24, behavior: CALM ? 'auto' : 'smooth' });
  };
  var io = new IntersectionObserver(function (es) {
    es.forEach(function (e) { if (e.isIntersecting) light(e.target.id); });
  }, { rootMargin: '-45% 0px -50% 0px' });
  Object.keys(byId).forEach(function (id) { var s = document.getElementById(id); if (s) io.observe(s); });
})();

// What scrolls into view rises into place, a beat apart. Marked here, not
// in the page: without the script, everything simply shows.
(function () {
  if (CALM || !('IntersectionObserver' in window)) return;
  var groups = [
    ['.feature .copy, .feature .visual', 0.12],
    ['.more .kicker, .more h2, .cards.strip, .more .after', 0.08], ['.cards:not(.strip) .card', 0.07],
    ['.reach', 0.09], ['.reachus .first', 0], ['.privacy .box, .faq .kicker, .faq h2, .faq .group, .faq .qa, .faq .after, .end .wrap > *', 0.06],
  ];
  var io = new IntersectionObserver(function (es) {
    es.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); } });
  }, { rootMargin: '0px 0px -6% 0px', threshold: 0 });
  document.documentElement.classList.add('js');
  groups.forEach(function (g) {
    var seen = new Map();
    document.querySelectorAll(g[0]).forEach(function (n) {
      var box = n.parentElement, k = seen.get(box) || 0; seen.set(box, k + 1);
      // Already on screen when the script arrives: it has been seen, leave it.
      if (n.getBoundingClientRect().top < window.innerHeight) return;
      n.classList.add('rv');
      n.style.setProperty('--d', (n.classList.contains('card') ? (k % 3) : Math.min(k, 5)) * g[1] + 's');
      io.observe(n);
    });
  });
})();

// Each page in two languages, at two addresses (the <link hreflang> in its
// head). An Italian browser, or the footer's switch remembered on this
// device, goes to the other one.
(function () {
  var PAGE = document.documentElement.getAttribute('lang') === 'it' ? 'it' : 'en';
  var twin = function (lang) {
    var l = document.querySelector('link[rel="alternate"][hreflang="' + lang + '"]');
    return l ? new URL(l.getAttribute('href'), location.href).pathname : null;
  };
  var saved = null;
  try { saved = localStorage.getItem('lang'); } catch (e) {}
  var it = twin('it');
  if (PAGE === 'en' && it && (saved === 'it' || (!saved && /^it\b/i.test(navigator.language || '')))) {
    location.replace(it + location.search + location.hash);
  }
  var sw = document.getElementById('lang');
  if (sw) sw.addEventListener('click', function () {
    var to = PAGE === 'it' ? 'en' : 'it';
    try { localStorage.setItem('lang', to); } catch (e) {}
    location.href = (twin(to) || (to === 'it' ? '/it/' : '/')) + location.search;
  });
})();
